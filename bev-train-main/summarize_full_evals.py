"""Summarize the full-split (80,019 question) evals produced by run_full_evals.sh.

Reads runs/ladder-<name>-full-eval.txt, extracts each run's final metrics line
(the single line matching "{'loss'"), and writes a compact markdown comparison
to runs/full-eval-summary.md plus stdout. Same ordering as run_full_evals.sh:
lora_mlp baseline loss softlabels layers24 layers28 ctx.
"""
from __future__ import annotations

import ast
import re
from pathlib import Path

RUNS = [
    ("lora_mlp", "lora attn_mlp r=16"),
    ("baseline", "baseline"),
    ("loss", "loss flags"),
    ("softlabels", "soft labels"),
    ("layers24", "layers 24"),
    ("layers28", "layers 28"),
    ("ctx", "ctx (8)"),
]
METRIC_KEYS = [
    "accuracy", "accuracy_choice", "accuracy_noul", "accuracy_score",
    "ece", "ece_choice", "ece_noul", "ece_score", "auc_noul", "loss",
]

HEAD = """\
# Full test-split eval summary (80,019 questions, seed 0)

Source: `runs/ladder-<name>-full-eval.txt` from `run_full_evals.sh`.
Grammar: same `best` checkpoints and `--config all` as the 1k sample in README,
but over the whole test split. `noul` = not-understood labels.

| Run | acc | acc choice | acc noul | acc score | ECE | ECE choice | ECE noul | ECE score | AUC noul | loss |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |
"""


def parse_metrics(path: Path) -> dict | None:
    """Return the dict from the single "{'loss': ...}" line, or None."""
    if not path.exists():
        return None
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        line = line.strip()
        if line.startswith("{'loss'"):
            try:
                return ast.literal_eval(line)
            except (ValueError, SyntaxError):
                return None
    return None


def fmt(v) -> str:
    if v is None or isinstance(v, float) and v != v:  # None or NaN
        return "—"
    return f"{v:.4f}"


def main() -> None:
    runs_dir = Path(__file__).resolve().parent / "runs"
    rows, parsed = [], {}
    for key, label in RUNS:
        m = parse_metrics(runs_dir / f"ladder-{key}-full-eval.txt")
        parsed[key] = m
        if m is None:
            rows.append(f"| {label} | — pending or failed — |")
            continue
        cells = [fmt(m.get(k)) for k in METRIC_KEYS[:-1]] + [fmt(m.get("loss"))]
        rows.append(f"| {label} | " + " | ".join(cells) + " |")

    out = HEAD + "\n".join(rows) + "\n"

    base = parsed.get("baseline")
    if isinstance(base, dict):
        diffs = []
        for key, label in RUNS:
            m = parsed[key]
            if key == "baseline" or not isinstance(m, dict):
                continue
            d = m.get("accuracy", 0) - base.get("accuracy", 0)
            diffs.append(f"**{label}** {d:+.4f}")
        out += "\nAccuracy delta vs baseline (pts of fraction): " + ", ".join(diffs) + "\n"

    out += ("\nReading so far:\n"
            "- (fill in once all 7 runs are done — this file is regenerated by summarize_full_evals.py)\n")

    dest = runs_dir / "full-eval-summary.md"
    dest.write_text(out, encoding="utf-8")
    print(out, end="")


if __name__ == "__main__":
    main()
